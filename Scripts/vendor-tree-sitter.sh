#!/bin/zsh
# Copies the tree-sitter runtime and grammar sources from Vendor/upstream into the
# app target. Re-run after updating a clone. See Vendor/README.md.
set -euo pipefail
cd "$(dirname "$0")/.."

UP=Vendor/upstream
RUNTIME_DST=Quill/Vendor/TreeSitter
GRAMMAR_DST=Quill/Vendor/Grammars
QUERY_DST=Quill/Resources/Queries
LICENSE_DST=Quill/Vendor/LICENSES

require() { [ -e "$1" ] || { echo "missing: $1 (see Vendor/README.md)"; exit 1; }; }

require "$UP/tree-sitter/lib/src/lib.c"
require "$UP/tree-sitter/lib/include/tree_sitter/api.h"

mkdir -p "$RUNTIME_DST/src" "$RUNTIME_DST/include/tree_sitter" "$GRAMMAR_DST/include" "$QUERY_DST" "$LICENSE_DST"

# --- Runtime: every translation unit except lib.c (lib.c #includes the others for unity builds).
for f in "$UP"/tree-sitter/lib/src/*.c "$UP"/tree-sitter/lib/src/*.h; do
  [ "$(basename "$f")" = "lib.c" ] && continue
  cp "$f" "$RUNTIME_DST/src/"
done
for sub in unicode portable; do
  if [ -d "$UP/tree-sitter/lib/src/$sub" ]; then
    mkdir -p "$RUNTIME_DST/src/$sub"
    cp "$UP/tree-sitter/lib/src/$sub"/*.h "$RUNTIME_DST/src/$sub/"
  fi
done
# The ICU headers carry their own license.
cp "$UP/tree-sitter/lib/src/unicode/LICENSE" "$LICENSE_DST/icu-unicode-LICENSE.txt"
cp "$UP/tree-sitter/lib/include/tree_sitter/api.h" "$RUNTIME_DST/include/tree_sitter/api.h"
cp "$UP/tree-sitter/LICENSE" "$LICENSE_DST/tree-sitter-LICENSE.txt"
cat > "$RUNTIME_DST/include/module.modulemap" <<'MAP'
module TreeSitter {
    header "tree_sitter/api.h"
    export *
}
MAP

# --- Grammars: name|upstream dir containing src/ and queries/|C symbol
GRAMMARS=(
  "swift|tree-sitter-swift|tree_sitter_swift"
  "python|tree-sitter-python|tree_sitter_python"
  "json|tree-sitter-json|tree_sitter_json"
  "markdown|tree-sitter-markdown/tree-sitter-markdown|tree_sitter_markdown"
  "markdown_inline|tree-sitter-markdown/tree-sitter-markdown-inline|tree_sitter_markdown_inline"
  "yaml|tree-sitter-yaml|tree_sitter_yaml"
)

HEADER="$GRAMMAR_DST/include/grammars.h"
{
  echo "// Generated by Scripts/vendor-tree-sitter.sh. Entry points of the compiled grammars."
  echo "#ifndef QUILL_GRAMMARS_H"
  echo "#define QUILL_GRAMMARS_H"
  echo "#include \"tree_sitter/api.h\""
  echo "#ifdef __cplusplus"
  echo "extern \"C\" {"
  echo "#endif"
} > "$HEADER"

API_VERSION=$(grep -E '#define TREE_SITTER_LANGUAGE_VERSION' "$RUNTIME_DST/include/tree_sitter/api.h" | awk '{print $3}')
MIN_VERSION=$(grep -E '#define TREE_SITTER_MIN_COMPATIBLE_LANGUAGE_VERSION' "$RUNTIME_DST/include/tree_sitter/api.h" | awk '{print $3}')
echo "runtime language version: $API_VERSION (min compatible $MIN_VERSION)"

for entry in "${GRAMMARS[@]}"; do
  name="${entry%%|*}"; rest="${entry#*|}"; dir="${rest%%|*}"; symbol="${rest#*|}"
  src="$UP/$dir/src"
  require "$src/parser.c"
  dst="$GRAMMAR_DST/$name"
  mkdir -p "$dst"
  # Rename the two conventional files so object names never collide across grammars.
  cp "$src/parser.c" "$dst/${name}_parser.c"
  [ -f "$src/scanner.c" ] && cp "$src/scanner.c" "$dst/${name}_scanner.c"
  # Any other C sources or headers the scanner includes (kept under their own names).
  for f in "$src"/*; do
    base="$(basename "$f")"
    case "$base" in
      parser.c|scanner.c|grammar.json|node-types.json|tree_sitter) ;;
      parser_abi*.c) ;; # alternate ABI builds of the same grammar; one parser is enough
      *.c|*.h) cp "$f" "$dst/" ;;
    esac
  done
  mkdir -p "$dst/tree_sitter"
  cp "$src"/tree_sitter/*.h "$dst/tree_sitter/"
  # Highlight query and license.
  queries="$UP/$dir/queries/highlights.scm"
  require "$queries"
  cp "$queries" "$QUERY_DST/${name}.highlights.scm"
  if [ "$name" = "json" ]; then
    # Later patterns win. Upstream lists the key pattern before "(string) @string",
    # which would turn every key into a plain string; re-assert it at the end.
    printf '\n; Added by Scripts/vendor-tree-sitter.sh: keys win over plain strings.\n(pair\n  key: (_) @string.special.key)\n' >> "$QUERY_DST/${name}.highlights.scm"
  fi
  # Injection query (which nodes hand off to another grammar), when the grammar has one.
  injections="$UP/$dir/queries/injections.scm"
  [ -f "$injections" ] && cp "$injections" "$QUERY_DST/${name}.injections.scm"
  repo_root="$UP/${dir%%/*}"
  [ -f "$repo_root/LICENSE" ] && cp "$repo_root/LICENSE" "$LICENSE_DST/${name}-LICENSE.txt"
  [ -f "$repo_root/LICENSE.md" ] && cp "$repo_root/LICENSE.md" "$LICENSE_DST/${name}-LICENSE.txt"
  echo "const TSLanguage *${symbol}(void);" >> "$HEADER"
  lang_version=$(grep -E '#define LANGUAGE_VERSION' "$dst/${name}_parser.c" | awk '{print $3}')
  echo "  $name: LANGUAGE_VERSION $lang_version ($symbol)"
  if [ -n "$lang_version" ] && [ -n "$API_VERSION" ] && [ -n "$MIN_VERSION" ]; then
    if [ "$lang_version" -gt "$API_VERSION" ] || [ "$lang_version" -lt "$MIN_VERSION" ]; then
      echo "  WARNING: $name grammar version $lang_version is outside [$MIN_VERSION, $API_VERSION]"
    fi
  fi
done

{
  echo "#ifdef __cplusplus"
  echo "}"
  echo "#endif"
  echo "#endif"
} >> "$HEADER"
cat > "$GRAMMAR_DST/include/module.modulemap" <<'MAP'
module TreeSitterGrammars {
    header "grammars.h"
    export *
}
MAP

echo "Vendored into $RUNTIME_DST, $GRAMMAR_DST and $QUERY_DST."
